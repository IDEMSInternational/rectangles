import { RandomState } from '@studio/engine/random/random-state';
import { referencePuzzlesToCheck } from '@studio/engine/reference-puzzles';
import { decodeParams } from '../params';
import { rectanglesGame } from '../rectangles-game';
import reference from '../testing/reference-puzzles.json';
import { generateRectangles } from './generate';

/** A solve move's rectangles, in a fixed order, to compare two solutions. */
function rectsOf(move: ReturnType<typeof rectanglesGame.solve>): string[] {
  return move?.kind === 'solve' ? move.rects.map((r) => JSON.stringify(r)).sort() : [];
}

/**
 * The recorded puzzles were generated by the original C code (see
 * tools/c-reference). The port must reproduce each one exactly: the
 * puzzle, its solution, and the solver finding that solution from the
 * puzzle alone (as Solve does for a puzzle typed in by hand). The
 * original's ambiguous puzzles ("a" in their settings, never offered in
 * the app) can have other solutions, so only their puzzle and solution are
 * checked. `npm test` checks a sample, `npm run test:puzzles` all of them.
 */
describe('Rectangles matches the original C code', () => {
  for (const ref of referencePuzzlesToCheck(reference)) {
    it(`${ref.params}#${ref.seed}`, () => {
      const params = decodeParams(ref.params);
      const puzzle = generateRectangles(params, new RandomState(ref.seed));
      expect(puzzle.description).toBe(ref.description);
      expect(puzzle.solution).toBe(ref.solution);
      if (!params.unique) return;
      const initial = rectanglesGame.newGame(params, ref.description);
      const solved = rectsOf(rectanglesGame.solve(initial));
      expect(solved.length).toBeGreaterThan(0);
      expect(solved).toEqual(rectsOf(rectanglesGame.solve(initial, ref.solution)));
    });
  }
});
